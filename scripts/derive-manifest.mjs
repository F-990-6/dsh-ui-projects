/**
 * Derive `src/client/manifest.generated.js` from `package.json` → `dsh.uiProject`.
 *
 * WHY THE MANIFEST LIVES IN package.json. It is the file the installer already reads and
 * validates when it admits a package, so it is the only place where a package's identity
 * (`name`, `version`) and the projects it declares sit in one document. A hand-written literal
 * inside the client bundle would be a second source for the same facts, and the only thing that
 * keeps two copies honest is a check — so the derivation IS the check, in the same shape the
 * project already uses for `boot.css`.
 *
 * The generated module carries `package` and `version` from `package.json` itself, which is why
 * a registration cannot claim an identity the installed package does not have.
 *
 *   node scripts/derive-manifest.mjs --package <dir>          # (re)write
 *   node scripts/derive-manifest.mjs --package <dir> --check   # report drift, change nothing
 *
 * A package without a `dsh.uiProject` block is not a UI project package: the tool says so,
 * writes nothing, and — if a stale generated file is lying around — removes it under `--check`'s
 * rules by failing loudly instead. Silence there would be the one outcome worth preventing: a
 * bundle that registers a project its package no longer declares.
 */
import { readFile, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const argv = process.argv.slice(2)
const checkOnly = argv.includes('--check')
const packageIndex = argv.indexOf('--package')
if (packageIndex < 0 || argv[packageIndex + 1] === undefined) {
  process.stderr.write('usage: node scripts/derive-manifest.mjs --package <dir> [--check]\n')
  process.exit(2)
}

const packageRoot = resolve(argv[packageIndex + 1])
const packageJsonPath = join(packageRoot, 'package.json')
const outFile = join(packageRoot, 'src', 'client', 'manifest.generated.js')

const pkg = JSON.parse(await readFile(packageJsonPath, 'utf8'))
const declared = pkg.dsh?.uiProject

if (declared === undefined) {
  if (existsSync(outFile)) {
    // A package that stopped declaring a project must not keep shipping a generated manifest:
    // the bundle would register a project nothing owns.
    if (checkOnly) {
      process.stdout.write(`manifest.generated.js is present but ${pkg.name} declares no dsh.uiProject\n`)
      process.exitCode = 1
    } else {
      await rm(outFile)
      process.stdout.write(`removed manifest.generated.js — ${pkg.name} declares no dsh.uiProject\n`)
    }
  } else {
    process.stdout.write(`${pkg.name} is not a UI project package (no dsh.uiProject); nothing to generate\n`)
  }
  process.exit(process.exitCode ?? 0)
}

/*
 * The field table comes from `src/host/manifest-schema.js` — the ONE place that says what a
 * manifest may contain, read here and by the conformance checker. A second list in this file would
 * be a second answer to the same question, and the two would disagree the first time a field was
 * added. Loaded dynamically because it sits next to the table it replaces, in a script whose other
 * imports are at the top.
 */
const { MANIFEST_FIELDS, validateManifest } = await import('../src/host/manifest-schema.js')
const ORDER = MANIFEST_FIELDS.map((entry) => entry.field)
const entries = ORDER.filter((key) => declared[key] !== undefined).map((key) => [key, declared[key]])

/*
 * The same validation the checker applies to an installed package, applied here at build time.
 * Generating a manifest the checker would refuse is a package that cannot be installed, and build
 * time is the cheapest place on earth to hear about a typo.
 */
const issues = validateManifest(declared)
if (issues.length > 0) {
  throw new Error(
    `[derive-manifest] ${pkg.name}: dsh.uiProject does not validate:\n` +
      issues
        .map((issue) => `[derive-manifest]   ${issue.field}: ${issue.message}\n[derive-manifest]     fix: ${issue.action}`)
        .join('\n'),
  )
}

const body = entries.map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`).join('\n')
const next = `/**
 * GENERATED by scripts/derive-manifest.mjs — do not edit.
 *
 * Source: ${pkg.name}@${pkg.version} → package.json → dsh.uiProject, with \`package\` and \`version\`
 * taken from the package's own manifest. Regenerate with:
 *   node scripts/derive-manifest.mjs --package "<path-to-package>"
 */
module.exports = {
  package: ${JSON.stringify(pkg.name)},
  version: ${JSON.stringify(pkg.version)},
${body}
}
`

const current = await readFile(outFile, 'utf8').catch(() => '')
if (next === current) {
  process.stdout.write(`manifest.generated.js is up to date — ${entries.length} declared field(s) + identity\n`)
} else if (checkOnly) {
  process.stdout.write(
    `manifest.generated.js is STALE for ${pkg.name} (${Buffer.byteLength(current, 'utf8')} bytes on disk, ` +
      `${Buffer.byteLength(next, 'utf8')} derived). Run: node scripts/derive-manifest.mjs --package ${packageRoot}\n`,
  )
  process.exitCode = 1
} else {
  await writeFile(outFile, next, 'utf8')
  process.stdout.write(`manifest.generated.js rewritten — ${entries.length} declared field(s) + identity\n`)
}
